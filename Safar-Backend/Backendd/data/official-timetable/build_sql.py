"""Build SQL that replaces Safar's stations/routes/trains/timetable with the
official Bangladesh Railway timetable (Time Table No. 54, effective 10 March 2025).

Inputs (same folder): trains.json, coords.json
Outputs: official_timetable.sql, stationCoords.js
"""
import json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
trains = json.load(open(os.path.join(HERE, 'trains.json')))
coords = json.load(open(os.path.join(HERE, 'coords.json')))
old_ids = json.load(open(os.path.join(HERE, 'old_station_ids.json')))     # {old_name: id}
old_seats = json.load(open(os.path.join(HERE, 'old_seats.json')))         # {train_code: [[class, seats]]}

# Old DB name -> new official name (same physical station keeps its old id,
# so existing tickets still point at the right place)
RENAMED = {
    'Comilla': 'Cumilla', 'Jessore': 'Jashore', 'Thakurgaon': 'Thakurgaon Road',
    'Sirajgonj': 'Sirajganj Bazar', 'Mohangonj': 'Mohanganj', 'Dewanganj': 'Dewanganj Bazar',
}

def db_name(name):
    return name.replace(' ', '_')

def q(s):
    return "'" + str(s).replace("'", "''") + "'"

def fmt(t):
    return f"{t[:2]}:{t[2:]}:00"

# ---- stations -------------------------------------------------------------
all_names = sorted({s[0] for t in trains.values() for s in t['stops']})
missing = [n for n in all_names if n not in coords]
if missing:
    sys.exit(f'No coordinates for: {missing}')

station_id = {}
for old, sid in old_ids.items():
    new = RENAMED.get(old.replace('_', ' '), old.replace('_', ' '))
    if new in all_names:
        station_id[new] = sid
next_id = 100
for n in all_names:
    if n not in station_id:
        station_id[n] = next_id
        next_id += 1

zone_of = {}
for t in trains.values():
    for s in t['stops']:
        zone_of.setdefault(s[0], 'East' if t['zone'] == 'east' else 'West')

# ---- distances ------------------------------------------------------------
def km(a, b):
    (la1, lo1), (la2, lo2) = coords[a], coords[b]
    p = math.pi / 180
    h = (math.sin((la2 - la1) * p / 2) ** 2 +
         math.cos(la1 * p) * math.cos(la2 * p) * math.sin((lo2 - lo1) * p / 2) ** 2)
    return 2 * 6371 * math.asin(math.sqrt(h)) * 1.15   # rail detour factor

KM_PER_UNIT = 40   # fare = class.cost_per_unit * units; Shovon Chair (50) * 8 units ~ Dhaka-Chattogram
dist = {}
for t in trains.values():
    names = [s[0] for s in t['stops']]
    cum = [0.0]
    for a, b in zip(names, names[1:]):
        cum.append(cum[-1] + km(a, b))
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            a, b = sorted((station_id[names[i]], station_id[names[j]]))
            d = cum[j] - cum[i]
            if (a, b) not in dist or d < dist[(a, b)]:
                dist[(a, b)] = d

# ---- seat classes for trains that are new to the database --------------------
def default_classes(t):
    dep = t['stops'][0][2]
    night = int(dep[:2]) >= 19 or int(dep[:2]) < 3
    cls = [[6, 60], [9, 50], [10, 40]]          # Shovon Chair, Snigdha, AC seat
    if night:
        cls.append([8, 24])                      # 1st Berth on overnight trains
    return cls

out = []
w = out.append
w('-- Official Bangladesh Railway intercity timetable (Time Table No. 54, effective 10.03.2025)')
w('-- Source: railway.gov.bd timetable PDFs. Generated by build_sql.py')
w('BEGIN;')
# Bookings made on the old data point at stations that no longer exist (Banani, Tejgaon):
# they were inside Dhaka, so move them to Dhaka (Kamalapur).
w(f"UPDATE seat_reservation SET from_station = '{station_id['Dhaka']}' WHERE from_station IN ('{old_ids.get('Banani', -1)}', '{old_ids.get('Tejgaon', -1)}');")
w(f"UPDATE seat_reservation SET to_station = '{station_id['Dhaka']}' WHERE to_station IN ('{old_ids.get('Banani', -1)}', '{old_ids.get('Tejgaon', -1)}');")
w('DELETE FROM time_table;')
w('DELETE FROM route_station;')
w('DELETE FROM distance_storage;')
codes = sorted(int(c) for c in trains)
keep_codes = ','.join(str(c) for c in codes)
w(f'DELETE FROM seat_coordinate WHERE layout_id IN (SELECT layout_id FROM layout WHERE train_code NOT IN ({keep_codes}));')
w(f'DELETE FROM layout WHERE train_code NOT IN ({keep_codes});')
w(f'DELETE FROM seat WHERE train_code NOT IN ({keep_codes});')
w(f'DELETE FROM train_class WHERE train_code NOT IN ({keep_codes});')
w('ALTER TABLE train DROP CONSTRAINT train_route_id_fkey;')
w('DELETE FROM route;')
w(f'DELETE FROM train WHERE train_code NOT IN ({keep_codes});')
w('DELETE FROM station;')

for n in all_names:
    la, lo = coords[n]
    w(f"INSERT INTO station (station_id, station_name, location, zone) VALUES ({station_id[n]}, {q(db_name(n))}, {q(f'{la:.5f},{lo:.5f}')}, {q(zone_of[n])});")

for c in codes:
    t = trains[str(c)]
    names = [s[0] for s in t['stops']]
    ids = [station_id[n] for n in names]
    route_name = f"{names[0]}-{names[-1]}"
    w(f"INSERT INTO route (route_id, route_name, total_station, order_of_stations) VALUES ({c}, {q(route_name)}, {len(ids)}, {q(' '.join(map(str, ids)))});")
    for sid in ids:
        w(f'INSERT INTO route_station (station_id, route_id) VALUES ({sid}, {c});')
    off = t['off_day'] or 'NONE'
    w(f"INSERT INTO train (train_code, name, off_day, route_id) VALUES ({c}, {q(t['name'])}, {q(off)}, {c}) "
      f"ON CONFLICT (train_code) DO UPDATE SET name = EXCLUDED.name, off_day = EXCLUDED.off_day, route_id = EXCLUDED.route_id;")
    for name, arr, dep in t['stops']:
        a = arr or dep
        d = dep or arr
        w(f'INSERT INTO time_table (train_code, station_id, arrival_time, departure_time, route_id) '
          f"VALUES ({c}, {station_id[name]}, {q(fmt(a))}, {q(fmt(d))}, {c});")
    if str(c) not in old_seats:
        for cls, seats in default_classes(t):
            w(f'INSERT INTO train_class (class_code, train_code) VALUES ({cls}, {c}) ON CONFLICT DO NOTHING;')
            w(f'INSERT INTO seat (total_seat, class_code, train_code) VALUES ({seats}, {cls}, {c}) ON CONFLICT DO NOTHING;')

w('ALTER TABLE train ADD CONSTRAINT train_route_id_fkey FOREIGN KEY (route_id) REFERENCES route(route_id);')
for (a, b), d in sorted(dist.items()):
    w(f'INSERT INTO distance_storage (from_station, to_station, distance_unit) VALUES ({a}, {b}, {max(1, round(d / KM_PER_UNIT))});')
w('COMMIT;')
open(os.path.join(HERE, 'official_timetable.sql'), 'w').write('\n'.join(out) + '\n')

# ---- frontend coordinates -------------------------------------------------
js = ['// Station coordinates [lat, lng] for the route map.',
      '// Source: OpenStreetMap (railway=station nodes via Overpass, a few via Nominatim), © OpenStreetMap contributors, ODbL.',
      '// Keys match the station names stored in the database (underscores, not spaces).',
      '// Generated together with the official timetable import.',
      'const STATION_COORDS = {']
for n in all_names:
    la, lo = coords[n]
    key = db_name(n)
    key = key if key.replace('_', '').isalnum() else json.dumps(key)
    js.append(f'  {key}: [{la:.4f}, {lo:.4f}],')
js += ['};', '',
       "const norm = (s) => String(s || '').trim().replace(/\\s+/g, '_').toLowerCase();",
       'const LOOKUP = Object.fromEntries(Object.entries(STATION_COORDS).map(([k, v]) => [norm(k), v]));', '',
       'export const coordsOf = (name) => LOOKUP[norm(name)] || null;', '',
       'export default STATION_COORDS;', '']
open(os.path.join(HERE, 'stationCoords.js'), 'w').write('\n'.join(js))
print(f'{len(codes)} trains, {len(all_names)} stations, {len(dist)} fare pairs')
